using System.Text.Json;

using Aris.Application.Addresses;
using Aris.Application.Addresses.Dtos;
using Aris.Application.Auditing;
using Aris.Application.Common;
using Aris.Domain.Entities;
using Aris.Infrastructure.Persistence;

using FluentValidation;

using Microsoft.EntityFrameworkCore;

namespace Aris.Infrastructure.Addresses;

/// <summary>
/// Address registration, search, detail, and retirement
/// (<c>ADR-01</c>–<c>ADR-03</c>, <c>SRCH-03</c>).
/// </summary>
public sealed class AddressService : IAddressService {
    private const string CreateAction = "CREATE_ADDRESS";
    private const string RetireAction = "RETIRE_ADDRESS";
    private const int MaxSearchResults = 500;
    private const int MaxLineageDepth = 20; // D9 / R17

    private readonly ArisDbContext _context;
    private readonly IAuditService _audit;
    private readonly IValidator<CreateAddressDto> _createValidator;
    private readonly IValidator<RetireAddressDto> _retireValidator;

    public AddressService(
        ArisDbContext context,
        IAuditService audit,
        IValidator<CreateAddressDto> createValidator,
        IValidator<RetireAddressDto> retireValidator) {
        _context = context;
        _audit = audit;
        _createValidator = createValidator;
        _retireValidator = retireValidator;
    }

    // ADR-01: Registers a new administrative address
    public async Task<Result<int>> CreateAsync(
        CreateAddressDto dto,
        int currentUserId,
        CancellationToken ct = default) {
        // 1. Verify that the user performing this is an active user
        if (!await IsActiveActorAsync(currentUserId, ct)) {
            return Result<int>.Failure("The authenticated user was not found or is not active.");
        }

        // 2. Validate input fields using FluentValidation
        var validation = await _createValidator.ValidateAsync(dto, ct);
        if (!validation.IsValid) {
            return Result<int>.Failure(validation.Errors.Select(e => e.ErrorMessage));
        }

        var addressCode = dto.AddressCode.Trim();

        // 3. AddressCode must be unique across the system
        if (await _context.Addresses.AnyAsync(a => a.AddressCode == addressCode, ct)) {
            return Result<int>.Failure($"Address code {addressCode} is already registered.");
        }

        var correlationId = Guid.NewGuid();
        var now = DateTime.UtcNow;

        // 4. Insert address and audit log together in one transaction
        await using var transaction = await _context.Database.BeginTransactionAsync(ct);
        try {
            // AddressText is a computed column generated by SQL Server using CONCAT_WS,
            // so it is never assigned in C#.
            var address = new Address {
                AddressCode = addressCode,
                AddressLine = dto.AddressLine.Trim(),
                Ward = dto.Ward.Trim(),
                District = string.IsNullOrWhiteSpace(dto.District) ? null : dto.District.Trim(),
                Province = dto.Province.Trim(),
                Status = "ACTIVE",
                ValidFrom = dto.ValidFrom,
                CreatedAt = now
            };

            _context.Addresses.Add(address);
            await _context.SaveChangesAsync(ct);

            await _audit.LogAsync(new AuditEntry {
                ActorUserId = currentUserId,
                Action = CreateAction,
                EntityType = "Address",
                EntityId = address.AddressId,
                DetailsJson = JsonSerializer.Serialize(new {
                    address.AddressCode,
                    address.AddressLine,
                    address.Ward,
                    address.District,
                    address.Province
                }),
                CorrelationId = correlationId
            }, ct);

            await transaction.CommitAsync(ct);
            return Result<int>.Success(address.AddressId);
        } catch (Exception ex) {
            await TryRollbackAsync(transaction, ct);
            await LogFailureAsync(currentUserId, CreateAction, null, correlationId, ex, ct);
            return Result<int>.Failure($"The address could not be registered: {ex.Message}");
        }
    }

    // Returns all ACTIVE addresses sorted alphabetically by AddressText
    public async Task<Result<IEnumerable<AddressDto>>> GetActiveAsync(
        CancellationToken ct = default) {
        var addresses = await _context.Addresses
            .AsNoTracking()
            .Where(a => a.Status == "ACTIVE")
            .OrderBy(a => a.AddressText)
            .Select(a => new AddressDto {
                AddressId = a.AddressId,
                AddressCode = a.AddressCode,
                AddressLine = a.AddressLine,
                AddressText = a.AddressText,
                Ward = a.Ward,
                District = a.District,
                Province = a.Province,
                Status = a.Status,
                ValidFrom = a.ValidFrom,
                ValidTo = a.ValidTo,
                ReplacedByAddressId = a.ReplacedByAddressId,
                DeactivatedAt = a.DeactivatedAt
            })
            .ToListAsync(ct);

        return Result<IEnumerable<AddressDto>>.Success(addresses);
    }

    // SRCH-03 / ADR-02: search by code, street, ward, district, province, or full text
    public async Task<Result<IEnumerable<AddressDto>>> SearchAsync(
        AddressSearchCriteria criteria,
        CancellationToken ct = default) {
        if (criteria is null) {
            return Result<IEnumerable<AddressDto>>.Failure("Search criteria are required.");
        }

        var query = _context.Addresses.AsNoTracking().AsQueryable();

        if (!string.IsNullOrWhiteSpace(criteria.Status)) {
            var status = criteria.Status.Trim().ToUpperInvariant();
            if (status is not ("ACTIVE" or "INACTIVE")) {
                return Result<IEnumerable<AddressDto>>.Failure(
                    "Status must be ACTIVE or INACTIVE.");
            }

            query = query.Where(a => a.Status == status);
        }

        if (!string.IsNullOrWhiteSpace(criteria.SearchText)) {
            var text = criteria.SearchText.Trim();

            query = query.Where(a =>
                a.AddressCode.Contains(text)
                || a.AddressLine.Contains(text)
                || a.Ward.Contains(text)
                || (a.District != null && a.District.Contains(text))
                || a.Province.Contains(text)
                || a.AddressText.Contains(text));
        }

        var addresses = await query
            .OrderBy(a => a.Status)
            .ThenBy(a => a.AddressText)
            .Take(MaxSearchResults)
            .Select(a => new AddressDto {
                AddressId = a.AddressId,
                AddressCode = a.AddressCode,
                AddressLine = a.AddressLine,
                AddressText = a.AddressText,
                Ward = a.Ward,
                District = a.District,
                Province = a.Province,
                Status = a.Status,
                ValidFrom = a.ValidFrom,
                ValidTo = a.ValidTo,
                ReplacedByAddressId = a.ReplacedByAddressId,
                DeactivatedAt = a.DeactivatedAt
            })
            .ToListAsync(ct);

        return Result<IEnumerable<AddressDto>>.Success(addresses);
    }

    // ADR-02: address profile plus current households and residents
    public async Task<Result<AddressDetailDto?>> GetByIdAsync(
        int addressId,
        CancellationToken ct = default) {
        var address = await _context.Addresses
            .AsNoTracking()
            .FirstOrDefaultAsync(a => a.AddressId == addressId, ct);

        if (address is null) {
            return Result<AddressDetailDto?>.Success(null);
        }

        var canonical = await ResolveCanonicalAsync(addressId, ct);
        string? canonicalText = null;

        if (canonical.HasValue) {
            var canonicalAddress = canonical.Value;
            canonicalText = await _context.Addresses
                .AsNoTracking()
                .Where(a => a.AddressId == canonicalAddress.AddressId)
                .Select(a => a.AddressText)
                .FirstOrDefaultAsync(ct);
        }

        string? replacedByText = null;

        if (address.ReplacedByAddressId is int replacedById) {
            replacedByText = await _context.Addresses
                .AsNoTracking()
                .Where(a => a.AddressId == replacedById)
                .Select(a => a.AddressText)
                .FirstOrDefaultAsync(ct);
        }

        // Households whose active HouseholdAddress points at this exact address.
        var households = await (
            from ha in _context.HouseholdAddresses.AsNoTracking()
            join h in _context.Households.AsNoTracking() on ha.HouseholdId equals h.HouseholdId
            where ha.AddressId == addressId
                && ha.Status == "ACTIVE"
                && h.Status == "ACTIVE"
            select new AddressHouseholdDto {
                HouseholdId = h.HouseholdId,
                Status = h.Status,
                HeadFullName = (
                    from m in _context.HouseholdMemberships
                    join c in _context.Citizens on m.CitizenId equals c.CitizenId
                    where m.HouseholdId == h.HouseholdId
                        && m.Status == "ACTIVE"
                        && m.Role == "HEAD"
                    select c.FullName).FirstOrDefault(),
                ActiveMemberCount = _context.HouseholdMemberships
                    .Count(m => m.HouseholdId == h.HouseholdId && m.Status == "ACTIVE")
            })
            .OrderBy(h => h.HouseholdId)
            .ToListAsync(ct);

        // Citizens whose active Residence points at this exact address.
        var residents = await (
            from r in _context.Residences.AsNoTracking()
            join c in _context.Citizens.AsNoTracking() on r.CitizenId equals c.CitizenId
            join m in _context.HouseholdMemberships.AsNoTracking()
                on r.CitizenId equals m.CitizenId
            where r.AddressId == addressId
                && r.Status == "ACTIVE"
                && m.Status == "ACTIVE"
            select new AddressResidentDto {
                CitizenId = c.CitizenId,
                NationalId = c.NationalId,
                FullName = c.FullName,
                HouseholdId = m.HouseholdId,
                Role = m.Role
            })
            .OrderBy(r => r.FullName)
            .ToListAsync(ct);

        return Result<AddressDetailDto?>.Success(new AddressDetailDto {
            AddressId = address.AddressId,
            AddressCode = address.AddressCode,
            AddressLine = address.AddressLine,
            Ward = address.Ward,
            District = address.District,
            Province = address.Province,
            AddressText = address.AddressText,
            Status = address.Status,
            ValidFrom = address.ValidFrom,
            ValidTo = address.ValidTo,
            ReplacedByAddressId = address.ReplacedByAddressId,
            ReplacedByAddressText = replacedByText,
            CreatedAt = address.CreatedAt,
            DeactivatedAt = address.DeactivatedAt,
            CanonicalAddressId = canonical is null ? null : canonical.Value.AddressId,
            CanonicalAddressText = canonicalText,
            CanonicalStatus = canonical is null ? null : canonical.Value.Status,
            CurrentHouseholds = households,
            CurrentResidents = residents
        });
    }

    // ADR-03 / D9: retire an address and point it at its successor
    public async Task<Result> RetireAsync(
        RetireAddressDto dto,
        int currentUserId,
        CancellationToken ct = default) {
        if (!await IsActiveActorAsync(currentUserId, ct)) {
            return Result.Failure("The authenticated user was not found or is not active.");
        }

        var validation = await _retireValidator.ValidateAsync(dto, ct);
        if (!validation.IsValid) {
            return Result.Failure(validation.Errors.Select(e => e.ErrorMessage));
        }

        var address = await _context.Addresses
            .FirstOrDefaultAsync(a => a.AddressId == dto.AddressId, ct);

        if (address is null) {
            return Result.Failure("Address not found.");
        }

        if (address.Status != "ACTIVE") {
            return Result.Failure("Only an ACTIVE address can be retired.");
        }

        var successor = await _context.Addresses
            .AsNoTracking()
            .FirstOrDefaultAsync(a => a.AddressId == dto.ReplacedByAddressId, ct);

        if (successor is null) {
            return Result.Failure("The successor address was not found.");
        }

        if (successor.AddressId == address.AddressId) {
            return Result.Failure("An address cannot be replaced by itself.");
        }

        if (successor.Status != "ACTIVE") {
            return Result.Failure("The successor address must be ACTIVE.");
        }

        if (dto.ValidTo < address.ValidFrom) {
            return Result.Failure(
                $"Valid-to date must be on or after {address.ValidFrom:yyyy-MM-dd}.");
        }

        var correlationId = Guid.NewGuid();
        var now = DateTime.UtcNow;
        var before = new {
            address.Status,
            address.ValidTo,
            address.ReplacedByAddressId
        };

        await using var transaction = await _context.Database.BeginTransactionAsync(ct);
        try {
            // One row changes state. Historical Residence / HouseholdAddress rows keep
            // the old AddressId; vw_AddressCanonical resolves them to the successor.
            address.Status = "INACTIVE";
            address.ValidTo = dto.ValidTo;
            address.ReplacedByAddressId = successor.AddressId;
            address.DeactivatedAt = now;

            await _context.SaveChangesAsync(ct);

            await _audit.LogAsync(new AuditEntry {
                ActorUserId = currentUserId,
                Action = RetireAction,
                EntityType = "Address",
                EntityId = address.AddressId,
                DetailsJson = JsonSerializer.Serialize(new {
                    before,
                    after = new {
                        address.Status,
                        address.ValidTo,
                        address.ReplacedByAddressId,
                        address.DeactivatedAt
                    },
                    successor = new {
                        successor.AddressId,
                        successor.AddressCode,
                        successor.AddressText
                    }
                }),
                CorrelationId = correlationId
            }, ct);

            await transaction.CommitAsync(ct);
            return Result.Success();
        } catch (DbUpdateConcurrencyException ex) {
            await TryRollbackAsync(transaction, ct);
            await LogFailureAsync(currentUserId, RetireAction, address.AddressId, correlationId, ex, ct);
            return Result.Failure(
                "The address was changed by someone else. Reload it and try again.");
        } catch (Exception ex) {
            await TryRollbackAsync(transaction, ct);
            await LogFailureAsync(currentUserId, RetireAction, address.AddressId, correlationId, ex, ct);
            return Result.Failure($"The address could not be retired: {ex.Message}");
        }
    }

    /// <summary>
    /// Follows <c>ReplacedByAddressId</c> to the terminal address (<c>D9</c>).
    /// Returns null for a missing row, a cycle, or a chain deeper than 20 levels.
    /// </summary>
    private async Task<(int AddressId, string Status)?> ResolveCanonicalAsync(
        int addressId,
        CancellationToken ct) {
        var visited = new HashSet<int>();
        var currentId = addressId;

        for (var depth = 0; depth <= MaxLineageDepth; depth++) {
            if (!visited.Add(currentId)) {
                return null;
            }

            var row = await _context.Addresses
                .AsNoTracking()
                .Where(a => a.AddressId == currentId)
                .Select(a => new { a.AddressId, a.Status, a.ReplacedByAddressId })
                .FirstOrDefaultAsync(ct);

            if (row is null) {
                return null;
            }

            if (row.ReplacedByAddressId is not int nextId) {
                return (row.AddressId, row.Status);
            }

            currentId = nextId;
        }

        return null;
    }

    private async Task<bool> IsActiveActorAsync(int userId, CancellationToken ct) {
        return await _context.UserAccounts
            .AsNoTracking()
            .AnyAsync(u => u.UserId == userId && u.Status == "ACTIVE", ct);
    }

    private async Task LogFailureAsync(
        int actorUserId,
        string action,
        int? entityId,
        Guid correlationId,
        Exception exception,
        CancellationToken ct) {
        var connectionString = _context.Database.GetConnectionString();
        if (string.IsNullOrWhiteSpace(connectionString)) {
            return;
        }

        await _audit.LogFailureIndependentAsync(connectionString, new AuditFailureEntry {
            ActorUserId = actorUserId,
            Action = action,
            EntityType = "Address",
            EntityId = entityId,
            DetailsJson = JsonSerializer.Serialize(new {
                reason = exception.Message,
                exception = exception.GetType().Name
            }),
            CorrelationId = correlationId
        }, ct);
    }

    private static async Task TryRollbackAsync(
        Microsoft.EntityFrameworkCore.Storage.IDbContextTransaction transaction,
        CancellationToken ct) {
        try {
            await transaction.RollbackAsync(ct);
        } catch {
            // A trigger may already have rolled the transaction back; keep the original error.
        }
    }
}